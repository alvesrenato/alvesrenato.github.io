// DOM Elements
const langButtons = document.querySelectorAll('.lang-btn');
const themeToggle = document.querySelector('.theme-toggle');
const themeIcon = document.querySelector('.theme-icon');
const html = document.documentElement;

// Current State
let currentLang = localStorage.getItem('lang') || detectDefaultLanguage();
let currentTheme = localStorage.getItem('theme') || 'dark';

// Auto-detect Language Logic
function detectDefaultLanguage() {
    const browserLang = navigator.language || navigator.userLanguage;
    const langCode = browserLang.toLowerCase().split('-')[0]; // Pega apenas 'pt', 'en', 'it', etc.

    if (langCode === 'it') {
        return 'it';
    } else if (langCode === 'pt') {
        return 'pt';
    } else {
        return 'en'; // Padrão para todos os outros países
    }
}

// Initialize
function init() {
    setLanguage(currentLang);
    setTheme(currentTheme);
    setupEventListeners();
    setupScrollReveal();
    setupSmoothScroll();
    setupWhatsappMask();
    setupDownloadCv();
    setupPhotoModal();
}

// Photo Modal
function setupPhotoModal() {
    const logoBtn = document.querySelector('.logo-btn');
    const modal = document.getElementById('photoModal');
    const closeBtn = document.querySelector('.photo-modal-close');
    const backdrop = document.querySelector('.photo-modal-backdrop');
    if (!logoBtn || !modal) return;

    function openModal() {
        modal.classList.add('active');
        modal.setAttribute('aria-hidden', 'false');
        document.body.style.overflow = 'hidden';
    }

    function closeModal() {
        modal.classList.remove('active');
        modal.setAttribute('aria-hidden', 'true');
        document.body.style.overflow = '';
    }

    logoBtn.addEventListener('click', openModal);
    closeBtn.addEventListener('click', closeModal);
    backdrop.addEventListener('click', closeModal);
    document.addEventListener('keydown', (e) => {
        if (e.key === 'Escape' && modal.classList.contains('active')) {
            closeModal();
        }
    });
}

// Download CV as PDF (uses the browser's print-to-PDF via the print stylesheet)
function setupDownloadCv() {
    const downloadBtn = document.querySelector('.js-download-cv');
    if (downloadBtn) {
        downloadBtn.addEventListener('click', () => {
            window.print();
        });
    }
}

// WhatsApp Masking
function setupWhatsappMask() {
    const whatsappButtons = document.querySelectorAll('.js-whatsapp');
    whatsappButtons.forEach((whatsappBtn) => {
        whatsappBtn.addEventListener('click', (e) => {
            e.preventDefault();
            // Desconstruindo o número para evitar detecção simples por robôs
            const country = "351";
            const number = "934192942";
            const url = `https://wa.me/${country}${number}`;
            window.open(url, '_blank');
        });
    });
}

// Language Switcher
function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('lang', lang);

    // Update buttons
    langButtons.forEach(btn => {
        btn.classList.toggle('active', btn.dataset.lang === lang);
    });

    // Update HTML lang attribute
    html.lang = lang;

    // Update all translatable elements
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.dataset.i18n;
        if (i18n[lang] && i18n[lang][key]) {
            // Add fade animation
            element.style.opacity = '0';
            element.style.transform = 'translateY(6px)';
            element.style.transition = 'opacity 0.15s ease, transform 0.15s ease';

            setTimeout(() => {
                element.textContent = i18n[lang][key];
                element.style.opacity = '1';
                element.style.transform = 'translateY(0)';
            }, 80);
        }
    });
}

// Theme Toggle
function setTheme(theme) {
    currentTheme = theme;
    localStorage.setItem('theme', theme);

    if (theme === 'light') {
        html.setAttribute('data-theme', 'light');
        themeIcon.className = 'fa-solid fa-sun theme-icon';
    } else {
        html.removeAttribute('data-theme');
        themeIcon.className = 'fa-solid fa-moon theme-icon';
    }
}

function toggleTheme() {
    const newTheme = currentTheme === 'dark' ? 'light' : 'dark';
    setTheme(newTheme);
}

// Event Listeners
function setupEventListeners() {
    // Language buttons
    langButtons.forEach(btn => {
        btn.addEventListener('click', () => {
            setLanguage(btn.dataset.lang);
        });
    });

    // Theme toggle
    themeToggle.addEventListener('click', toggleTheme);

    // Navigation scroll effect
    let lastScroll = 0;
    const nav = document.querySelector('.nav');

    window.addEventListener('scroll', () => {
        const currentScroll = window.pageYOffset;

        if (currentScroll > 100) {
            nav.style.boxShadow = '0 4px 20px rgba(0, 0, 0, 0.1)';
        } else {
            nav.style.boxShadow = 'none';
        }

        lastScroll = currentScroll;
    });
}

// Smooth Scroll
function setupSmoothScroll() {
    document.querySelectorAll('a[href^="#"]').forEach(anchor => {
        anchor.addEventListener('click', function (e) {
            e.preventDefault();
            const target = document.querySelector(this.getAttribute('href'));
            if (target) {
                const offsetTop = target.offsetTop - 80;
                window.scrollTo({
                    top: offsetTop,
                    behavior: 'smooth'
                });
            }
        });
    });
}

// Scroll Reveal Animation
function setupScrollReveal() {
    const observerOptions = {
        root: null,
        rootMargin: '0px',
        threshold: 0.1
    };

    const observer = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                entry.target.classList.add('active');
                observer.unobserve(entry.target);
            }
        });
    }, observerOptions);

    // Add reveal class to elements
    const revealElements = document.querySelectorAll(
        '.section-header, .about-text, .about-highlights, .skill-category, ' +
        '.timeline-item, .education-card, .contact-content'
    );

    revealElements.forEach((el, index) => {
        el.classList.add('reveal');
        el.style.transitionDelay = `${Math.min(index * 0.05, 0.2)}s`;
        observer.observe(el);
    });
}

// Typing Effect for Hero (Optional enhancement)
function typeWriter(element, text, speed = 50) {
    let i = 0;
    element.textContent = '';

    function type() {
        if (i < text.length) {
            element.textContent += text.charAt(i);
            i++;
            setTimeout(type, speed);
        }
    }

    type();
}

// Parallax Effect for Hero Background
function setupParallax() {
    const heroBg = document.querySelector('.hero-bg');

    window.addEventListener('mousemove', (e) => {
        const x = e.clientX / window.innerWidth;
        const y = e.clientY / window.innerHeight;

        heroBg.style.transform = `translate(${x * 20}px, ${y * 20}px)`;
    });
}

// Active Section Highlight in Navigation
function setupActiveSection() {
    const sections = document.querySelectorAll('section[id]');

    window.addEventListener('scroll', () => {
        let current = '';

        sections.forEach(section => {
            const sectionTop = section.offsetTop;
            const sectionHeight = section.clientHeight;

            if (pageYOffset >= sectionTop - 200) {
                current = section.getAttribute('id');
            }
        });
    });
}

// Initialize everything when DOM is ready
document.addEventListener('DOMContentLoaded', init);

